import { readFileSync } from 'node:fs'
import { randomUUID } from 'node:crypto'
import { test, expect } from '@playwright/test'
import en from '../src/locales/i18n.en.js'

test('local CDC changes stay in the draft until saved and disable incompatible settings', async ({ page, request }, info) => {
  const password = readFileSync(process.env.MOKYU_TEST_PASSWORD_FILE!, 'utf8').trim()
  const origin = process.env.MOKYU_TEST_WEB!
  const auth = await request.post('/api/v1/auth/login', { headers: { Origin: origin }, data: { username: 'tester', password } })
  expect(auth.status()).toBe(200)
  const headers = { Origin: origin, 'X-CSRF-Token': (await auth.json()).csrf_token }
  expect((await request.put('/api/v1/account', { headers, data: { display_name: '', locale: 'en', theme: 'light', avatar_email: '', avatar_enabled: false } })).ok()).toBe(true)
  const name = 'raw-ui-' + randomUUID().slice(0, 8)
  const created = await request.post('/api/v1/storages', { headers, data: { name, type: 'local', path: process.env.MOKYU_TEST_FSYNC_ROOT + '/' + name, initialize: true } })
  expect(created.status()).toBe(201)
  const profileUrl = '/api/v1/storages/' + name + '/profile'
  const original = await (await request.get(profileUrl)).json()
  expect(original.cdc_enabled).toBe(true)
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/login')
  await page.getByRole('textbox', { name: en.username, exact: true }).fill('tester')
  await page.getByRole('textbox', { name: en.password, exact: true }).fill(password)
  await page.getByRole('button', { name: en.signIn, exact: true }).click()
  await expect(page).toHaveURL(/\/overview$/)
  await page.goto('/storages?edit=' + name)
  const editor = page.getByRole('dialog', { name: en.editStore, exact: true })
  const cdc = editor.getByRole('switch', { name: en.profile_cdc_enabled, exact: true })
  await expect(cdc).toBeChecked()
  const dedup = editor.getByRole('switch', { name: en.profile_deduplication_enabled, exact: true })
  await expect(dedup).toBeChecked()
  await expect(dedup).toBeDisabled()
  await editor.locator('details.profile-group').nth(1).locator('summary').click()
  const compression = editor.getByRole('switch', { name: en.profile_compression_enabled, exact: true })
  await compression.click()
  await expect(compression).toBeChecked()
  await cdc.click()
  await expect(dedup).not.toBeChecked()
  await expect(dedup).toBeEnabled()
  await expect(compression).not.toBeChecked()
  await expect(compression).toBeDisabled()
  await expect(editor.getByRole('combobox', { name: en.storeCurrentKey, exact: true })).toBeDisabled()
  const storageType = editor.getByRole('combobox', { name: en.storeType, exact: true })
  await expect(storageType).toBeEnabled()
  await storageType.click()
  await page.getByRole('option', { name: en.storeType_s3, exact: true }).click()
  await expect(editor.getByText(en.storeRelocationHint, { exact: true })).toBeVisible()
  for (const width of [1440, 1024, 768, 640, 390, 320]) {
    await page.setViewportSize({ width, height: 900 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await expect(editor.getByText(en.storeRelocationHint, { exact: true })).toBeVisible()
  }
  await editor.screenshot({ path: info.outputPath('storage-relocation-mobile.png') })
  await page.setViewportSize({ width: 1280, height: 900 })
  await expect(cdc).not.toBeChecked()
  await expect(compression).not.toBeChecked()
  await storageType.click()
  await page.getByRole('option', { name: en.storeType_local, exact: true }).click()
  await expect(editor.getByText(en.storeRelocationHint, { exact: true })).toHaveCount(0)
  await expect(cdc).not.toBeChecked()
  expect((await (await request.get(profileUrl)).json()).revision).toBe(original.revision)
  await editor.screenshot({ path: info.outputPath('raw-settings-desktop.png') })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await editor.screenshot({ path: info.outputPath('raw-settings-mobile.png') })
  await editor.getByRole('button', { name: en.cancel, exact: true }).click()
  expect((await (await request.get(profileUrl)).json()).cdc_enabled).toBe(true)
  await page.goto('/storages?edit=' + name)
  await expect(cdc).toBeChecked()
  await cdc.click()
  await dedup.click()
  const saved = page.waitForResponse(reply => reply.url().endsWith('/api/v1/storages/' + name) && reply.request().method() === 'PUT')
  await editor.getByRole('button', { name: en.save, exact: true }).click()
  expect((await saved).status()).toBe(200)
  await expect(editor).toHaveCount(0)
  const current = await (await request.get(profileUrl)).json()
  expect(current.cdc_enabled).toBe(false)
  expect(current.deduplication_enabled).toBe(true)
  expect(current.compression_enabled).toBe(false)
  expect(current.revision).toBe(original.revision + 1)
  expect(errors).toEqual([])
})
