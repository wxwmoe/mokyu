import { readFileSync } from 'node:fs'
import { test, expect } from '@playwright/test'
import en from '../src/locales/i18n.en.js'
import zh from '../src/locales/i18n.zh-CN.js'
import ja from '../src/locales/i18n.ja.js'

test.skip(!process.env.MOKYU_TEST_IMAGE_FIXTURE, 'Requires an isolated image bucket and public input')

test('create rules with forms and edit, preview and export every imported style', async ({ page, request }, info) => {
  test.setTimeout(300000)
  const fixture = JSON.parse(readFileSync(process.env.MOKYU_TEST_IMAGE_FIXTURE!, 'utf8'))
  const password = readFileSync(process.env.MOKYU_TEST_PASSWORD_FILE!, 'utf8').trim()
  const source = process.env.MOKYU_TEST_IMAGE_STYLES!
  const names = readFileSync(source, 'utf8').split(/\r?\n/).filter(v => v.trim()).map(v => v.split(',')[0]!.split(':')[1]!.trim())
  expect(names).toHaveLength(50)
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  const login = await request.post('/api/v1/auth/login', { headers: { Origin: process.env.MOKYU_TEST_WEB! }, data: { username: 'tester', password } })
  expect(login.status()).toBe(200)
  const headers = { Origin: process.env.MOKYU_TEST_WEB!, 'X-CSRF-Token': (await login.json()).csrf_token }
  async function preferences(locale: string, theme: string) {
    expect((await request.put('/api/v1/account', { headers, data: { display_name: '', locale, theme, avatar_email: '', avatar_enabled: false } })).ok()).toBeTruthy()
  }
  await preferences('en', 'light')
  await page.goto('/login')
  await page.getByLabel(en.username).fill('tester')
  await page.getByLabel(en.password, { exact: true }).fill(password)
  await page.getByRole('button', { name: en.signIn, exact: true }).click()
  await expect(page).toHaveURL(/\/overview$/)
  await page.goto('/buckets/' + fixture.id)
  await page.getByRole('tab', { name: en.imageTitle, exact: true }).click()
  const panel = page.getByRole('tabpanel'), dialog = page.getByRole('dialog')
  await expect(panel.getByRole('heading', { name: en.imageTitle, exact: true })).toBeVisible()
  const base = '/api/v1/buckets/' + fixture.id + '/image-processing'
  const pixels = panel.getByRole('spinbutton', { name: en.imagePixelLimit, exact: true })
  await expect(pixels).toHaveValue('150')
  await pixels.fill('12.5')
  await panel.getByRole('button', { name: en.save, exact: true }).click()
  await expect.poll(async () => (await (await request.get(base + '/styles')).json()).settings.policy.max_pixels).toBe(12500000)
  await pixels.fill('150')
  await panel.getByRole('button', { name: en.save, exact: true }).click()
  await expect.poll(async () => (await (await request.get(base + '/styles')).json()).settings.policy.max_pixels).toBe(150000000)
  async function choose(scope: typeof dialog, label: string, option: string) {
    await scope.getByRole('combobox', { name: label, exact: true }).click()
    await page.getByRole('option', { name: option, exact: true }).click()
  }
  await panel.getByRole('button', { name: en.imageAddStyle, exact: true }).click()
  await dialog.getByRole('textbox', { name: en.imageName, exact: true }).fill('Form.Only')
  await dialog.getByRole('button', { name: en.imageOperation_resize, exact: true }).click()
  await dialog.getByRole('spinbutton', { name: en.imageWidth, exact: true }).fill('500')
  await dialog.getByRole('spinbutton', { name: en.imageHeight, exact: true }).fill('500')
  await expect(dialog.getByRole('checkbox', { name: en.imageUpscale, exact: true })).not.toBeChecked()
  await dialog.getByRole('button', { name: en.imageOperation_crop, exact: true }).click()
  await dialog.getByRole('spinbutton', { name: en.imageWidth, exact: true }).last().fill('200')
  await dialog.getByRole('spinbutton', { name: en.imageHeight, exact: true }).last().fill('150')
  await choose(dialog, en.imageAnchor, en.imageAnchor_northwest)
  await dialog.getByRole('button', { name: en.imageOperation_background, exact: true }).click()
  const color = dialog.getByLabel(en.imageBackground, { exact: true })
  await color.fill('#c85a89')
  await expect(dialog.getByText('#C85A89', { exact: true })).toBeVisible()
  await color.focus()
  await expect(color).toBeFocused()
  const chip = await dialog.locator('.color-chip').boundingBox()
  expect(chip?.width).toBeGreaterThanOrEqual(24)
  expect(chip?.height).toBeGreaterThanOrEqual(24)
  await choose(dialog, en.imageOutput, en.imageFormat_jpeg)
  await choose(dialog, en.imageQualityMode, en.imageQuality_exact)
  await dialog.getByRole('spinbutton', { name: en.imageQualityValue, exact: true }).fill('91')
  await dialog.getByRole('checkbox', { name: en.imageProgressive, exact: true }).check()
  await dialog.getByRole('button', { name: en.imageAddStage, exact: true }).click()
  await choose(dialog.locator('.image-stage').last(), en.imageOutput, en.imageFormat_webp)
  await dialog.locator('.image-stage').last().getByRole('button', { name: en.imageMoveUp, exact: true }).click()
  await dialog.locator('.image-stage').first().getByRole('button', { name: en.imageMoveDown, exact: true }).click()
  await dialog.screenshot({ path: info.outputPath('image-rule-editor.png') })
  await dialog.getByRole('button', { name: en.save, exact: true }).click()
  await expect(dialog).toHaveCount(0)
  let rows = (await (await request.get(base + '/styles')).json()).styles
  expect(rows[0].rule.stages[0]).toMatchObject({ format: 'jpeg', quality: 91, progressive: true })
  expect(rows[0].rule.stages[1].format).toBe('webp')
  expect(rows[0].rule.stages[0].operations).toContainEqual({ operation: 'background', color: 'c85a89' })
  expect(rows[0].rule.stages[0].operations).toContainEqual({ operation: 'crop', width: 200, height: 150, anchor: 'northwest' })
  await panel.getByRole('button', { name: en.imageImport, exact: true }).click()
  const picker = panel.getByLabel(en.imageStyleFile, { exact: true })
  await picker.focus()
  await expect(picker).toBeFocused()
  await picker.setInputFiles(source)
  await expect(panel.getByRole('button', { name: en.imageApplySelected, exact: true })).toBeEnabled()
  await panel.getByRole('button', { name: en.imageApplySelected, exact: true }).click()
  await expect(panel.getByRole('button', { name: en.imageApplied, exact: true })).toBeDisabled()
  await panel.getByRole('button', { name: en.imageImport, exact: true }).click()
  for (const name of names) {
    await panel.getByRole('textbox', { name: en.imageNamePrefix, exact: true }).fill(name)
    await panel.getByRole('button', { name: en.imageSearch, exact: true }).click()
    await panel.getByRole('button', { name: en.imageEditStyle.replace('{name}', name), exact: true }).click()
    await expect(dialog.getByRole('textbox', { name: en.imageName, exact: true })).toHaveValue(name)
    const stage = dialog.locator('.image-stage').last()
    await choose(stage, en.imageQualityMode, en.imageQuality_exact)
    await stage.getByRole('spinbutton', { name: en.imageQualityValue, exact: true }).fill('89')
    await dialog.getByRole('textbox', { name: en.imagePreviewKey, exact: true }).fill('public.jpg')
    const response = page.waitForResponse(v => v.url().endsWith('/image-processing/preview') && v.request().method() === 'POST')
    await dialog.getByRole('button', { name: en.imagePreview, exact: true }).click()
    const result = await response
    expect(result.status(), name + ': ' + (result.status() === 200 ? '' : await result.text())).toBe(200)
    const output = JSON.parse(result.headers()['x-mokyu-image-output']!)
    const img = dialog.getByRole('img', { name: en.imagePreviewOutput, exact: true })
    await expect.poll(() => img.evaluate((el: HTMLImageElement) => [el.naturalWidth, el.naturalHeight]), { message: name }).toEqual([output.width, output.height])
    await dialog.getByRole('button', { name: en.save, exact: true }).click()
    await expect(dialog).toHaveCount(0)
  }
  await panel.getByRole('textbox', { name: en.imageNamePrefix, exact: true }).fill('')
  await panel.getByRole('button', { name: en.imageSearch, exact: true }).click()
  await expect.poll(async () => (await (await request.get(base + '/styles?limit=128')).json()).styles.length).toBe(51)
  const download = page.waitForEvent('download')
  await panel.getByRole('link', { name: en.imageExportAll, exact: true }).click()
  const file = await download
  expect(await file.failure()).toBeNull()
  const text = readFileSync((await file.path())!, 'utf8')
  expect(text.split('\n').filter(Boolean)).toHaveLength(51)
  expect(text).toBe(await (await request.get(base + '/styles/export')).text())
  expect(text.split('\n').filter(Boolean).every(v => /^styleName: [^,]+, styleBody: mokyu\/v1\//.test(v))).toBeTruthy()
  for (const [locale, theme, width, labels] of [['en', 'light', 1280, en], ['zh-CN', 'dark', 375, zh], ['ja', 'light', 768, ja]] as const) {
    await preferences(locale, theme)
    await page.setViewportSize({ width, height: 900 })
    await page.goto('/buckets/' + fixture.id)
    await page.getByRole('tab', { name: labels.imageTitle, exact: true }).click()
    await expect(panel.getByRole('heading', { name: labels.imageTitle, exact: true })).toBeVisible()
    await expect(panel.getByRole('checkbox', { name: labels.imageEnabled, exact: true })).toBeVisible()
    await expect(panel.getByRole('spinbutton', { name: labels.imagePixelLimit, exact: true })).toHaveValue('150')
    await expect(panel.getByRole('button', { name: labels.imageAddStyle, exact: true })).toBeEnabled()
    await expect(panel.locator('tbody tr')).toHaveCount(50)
    const searchField = await panel.getByRole('textbox', { name: labels.imageNamePrefix, exact: true }).boundingBox()
    const searchButton = await panel.getByRole('button', { name: labels.imageSearch, exact: true }).boundingBox()
    expect(Math.abs(searchField!.y + searchField!.height - searchButton!.y - searchButton!.height)).toBeLessThan(2)
    const previous = await panel.getByRole('button', { name: labels.previous, exact: true }).boundingBox()
    const next = await panel.getByRole('button', { name: labels.next, exact: true }).boundingBox()
    expect(next!.x - previous!.x - previous!.width).toBeGreaterThanOrEqual(8)
    await panel.getByRole('checkbox', { name: labels.imageEnabled, exact: true }).scrollIntoViewIfNeeded()
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
    const screenshot = info.outputPath('image-settings-' + locale + '.png')
    await page.screenshot({ path: screenshot })
    await info.attach('image-settings-' + locale, { path: screenshot, contentType: 'image/png' })
  }
  expect(errors).toEqual([])
})
