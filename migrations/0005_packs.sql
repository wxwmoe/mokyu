CREATE TABLE packs (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    storage_id uuid NOT NULL UNIQUE,
    algorithm text NOT NULL CHECK (algorithm IN ('none','aes-256-gcm','chacha20-poly1305')),
    key_id text NOT NULL,
    raw_size bigint NOT NULL CHECK (raw_size>0),
    stored_size bigint,
    compressed boolean NOT NULL DEFAULT false,
    nonce bytea CHECK (nonce IS NULL OR octet_length(nonce)=12),
    digest bytea CHECK (digest IS NULL OR octet_length(digest)=32),
    member_count integer NOT NULL CHECK (member_count>=2),
    state text NOT NULL CHECK (state IN ('preparing','ready','retired','deleting','deleted')),
    created_at timestamptz NOT NULL DEFAULT now(),
    unreferenced_at timestamptz,
    deleted_at timestamptz
);
