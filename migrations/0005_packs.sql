-- Changes, including multipart boundary replacement, enqueue work in the same transaction.
CREATE FUNCTION enqueue_pack_extents() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    PERFORM id FROM chunks WHERE id IN (SELECT chunk_id FROM changed) ORDER BY id FOR UPDATE;
    UPDATE chunks SET reference_changed_at=now() WHERE id IN (SELECT chunk_id FROM changed);
    INSERT INTO pack_changes(pack_id,reason)
        SELECT DISTINCT c.pack_id,CASE WHEN TG_OP='DELETE' THEN 'reclaim' ELSE 'reuse' END FROM changed e JOIN chunks c ON c.id=e.chunk_id WHERE c.pack_id IS NOT NULL
        ON CONFLICT(pack_id) DO UPDATE SET generation=pack_changes.generation+1,next_check_at=now(),reason=CASE WHEN EXCLUDED.reason='reuse' THEN 'reuse' ELSE pack_changes.reason END;
    INSERT INTO pack_maintenance(stream_id,reason)
        SELECT DISTINCT e.stream_id,'repack' FROM changed x JOIN extents e ON e.chunk_id=x.chunk_id
        JOIN streams s ON s.id=e.stream_id WHERE s.state='ready'
        ON CONFLICT(stream_id) DO UPDATE SET generation=pack_maintenance.generation+1,cursor=0,updated_at=now(),next_check_at=now();
    RETURN NULL;
END $$;
CREATE TRIGGER pack_extents_insert AFTER INSERT ON extents REFERENCING NEW TABLE AS changed FOR EACH STATEMENT EXECUTE FUNCTION enqueue_pack_extents();
CREATE TRIGGER pack_extents_delete AFTER DELETE ON extents REFERENCING OLD TABLE AS changed FOR EACH STATEMENT EXECUTE FUNCTION enqueue_pack_extents();
CREATE TRIGGER pack_extents_update AFTER UPDATE ON extents REFERENCING NEW TABLE AS changed FOR EACH STATEMENT EXECUTE FUNCTION enqueue_pack_extents();
CREATE FUNCTION enqueue_pack_stream() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.state='ready' AND OLD.state IS DISTINCT FROM NEW.state THEN
        INSERT INTO pack_maintenance(stream_id) SELECT NEW.id WHERE NEW.kind='object' AND EXISTS(SELECT 1 FROM extents WHERE stream_id=NEW.id AND chunk_id IS NOT NULL OFFSET 1)
            ON CONFLICT(stream_id) DO UPDATE SET generation=pack_maintenance.generation+1,cursor=0,reason='pack',updated_at=now(),next_check_at=now();
        INSERT INTO pack_changes(pack_id)
            SELECT DISTINCT c.pack_id FROM extents e JOIN chunks c ON c.id=e.chunk_id WHERE e.stream_id=NEW.id AND c.pack_id IS NOT NULL
            ON CONFLICT(pack_id) DO UPDATE SET generation=pack_changes.generation+1,next_check_at=now(),reason='reuse';
    END IF;
    RETURN NULL;
END $$;
CREATE TRIGGER pack_stream_ready AFTER UPDATE OF state ON streams FOR EACH ROW EXECUTE FUNCTION enqueue_pack_stream();
